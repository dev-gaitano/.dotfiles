-- Read the colors generated by pywal so border colors keep updating with the
-- existing ~/.cache/wal/colors-hyprland.conf file.
local function wal_color(name, fallback)
  local file = io.open(os.getenv("HOME") .. "/.cache/wal/colors-hyprland.conf", "r")
  if not file then return fallback end

  for line in file:lines() do
    local value = line:match("^%$" .. name .. "%s*=%s*(.-)%s*$")
    if value then
      file:close()
      return value
    end
  end

  file:close()
  return fallback
end

